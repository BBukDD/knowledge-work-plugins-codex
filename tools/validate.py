from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

FRONTMATTER = re.compile(r"\A---\nname: ([a-z0-9-]+)\ndescription: ([^\n]+)\n---\n")
MARKDOWN_LINK = re.compile(r"\]\(([^)]+)\)")
FORBIDDEN_NAMES = {".mcp.json", ".claude-plugin", "marketplace.json"}
EXPECTED_MODULES = (
    "bio-research", "cowork-plugin-management", "customer-support", "data", "design",
    "engineering", "enterprise-search", "finance", "human-resources", "legal", "marketing",
    "operations", "pdf-viewer", "product-management", "productivity", "sales", "small-business",
)
PINNED_SOURCE_SHA = "33d3dea41a341b341d4f5da2e8801ae0c89be2b8"
GENERATED_MARKER = "Generated by tools/build.py for Codex.\n"
INVENTORY_START = "<!-- codex-package-sha256-v1\n"


def package_inventory_errors(package: Path) -> list[str]:
    notice = package / "NOTICE.md"
    try:
        notice_text = notice.read_text(encoding="utf-8")
    except OSError as error:
        return [f"{notice}: {error}"]
    _, marker, tail = notice_text.partition(INVENTORY_START)
    if not marker or notice_text.count(INVENTORY_START) != 1 or not tail.endswith("\n-->\n"):
        return [f"{notice}: package SHA256 inventory is missing or malformed"]
    try:
        inventory = json.loads(tail.removesuffix("\n-->\n"))
    except json.JSONDecodeError as error:
        return [f"{notice}: invalid package SHA256 inventory: {error}"]
    if not isinstance(inventory, dict):
        return [f"{notice}: package SHA256 inventory must be an object"]
    actual: dict[str, str] = {}
    errors: list[str] = []
    for path in sorted(package.rglob("*")):
        if path.is_symlink():
            errors.append(f"{path}: symlink in generated package")
        elif path.is_file() and path != notice:
            try:
                actual[path.relative_to(package).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
            except OSError as error:
                errors.append(f"{path}: {error}")
    for relative in sorted(actual.keys() | inventory.keys()):
        if inventory.get(relative) != actual.get(relative):
            errors.append(f"{package / relative}: SHA256 inventory mismatch")
    return errors


def validate_package(package: Path) -> list[str]:
    errors: list[str] = []
    manifest_path = package / "plugin.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return [f"{manifest_path}: {error}"]
    if not isinstance(manifest, dict):
        return [f"{manifest_path}: plugin manifest must be a JSON object"]
    if manifest.get("name") != package.name:
        errors.append(f"{manifest_path}: package name mismatch")
    if manifest.get("version") != "0.1.0":
        errors.append(f"{manifest_path}: expected adaptation version 0.1.0")
    if manifest.get("license") != "Apache-2.0":
        errors.append(f"{manifest_path}: expected Apache-2.0 license")
    if not str(manifest.get("description", "")).startswith("Unofficial Codex adaptation"):
        errors.append(f"{manifest_path}: adaptation provenance is missing")
    expected_repository = (
        "https://github.com/anthropics/knowledge-work-plugins/tree/"
        f"{PINNED_SOURCE_SHA}/{package.name.removeprefix('kw-')}"
    )
    if manifest.get("repository") != expected_repository:
        errors.append(f"{manifest_path}: upstream source URL must use the pinned revision")
    for required in ("LICENSE", "NOTICE.md", "CONNECTORS.md", ".codex-adapter-generated"):
        if not (package / required).is_file():
            errors.append(f"{package}: missing {required}")
    marker_path = package / ".codex-adapter-generated"
    if marker_path.is_file() and marker_path.read_text(encoding="utf-8") != GENERATED_MARKER:
        errors.append(f"{marker_path}: generator marker mismatch")
    errors.extend(package_inventory_errors(package))
    for item in package.rglob("*"):
        if item.name in FORBIDDEN_NAMES:
            errors.append(f"{item}: forbidden Claude connector or marketplace file")
    skills_root = package / "skills"
    if not skills_root.is_dir():
        return [*errors, f"{skills_root}: skills directory missing"]
    skill_dirs = sorted(path for path in skills_root.iterdir() if path.is_dir())
    if not skill_dirs:
        errors.append(f"{skills_root}: no skills found")
    for skill in skill_dirs:
        wrapper_path = skill / "SKILL.md"
        if not wrapper_path.is_file():
            errors.append(f"{skill}: SKILL.md missing")
            continue
        wrapper = wrapper_path.read_text(encoding="utf-8")
        match = FRONTMATTER.match(wrapper)
        if match is None or match.group(1) != skill.name:
            errors.append(f"{wrapper_path}: invalid Codex skill frontmatter")
        else:
            try:
                description = json.loads(match.group(2))
            except json.JSONDecodeError:
                description = ""
            if not isinstance(description, str) or not description or len(description) > 1024:
                errors.append(f"{wrapper_path}: invalid skill description")
        if not all(
            token in wrapper
            for token in ("$ARGUMENTS", "~~", "CONNECTORS.md", "authorization", "auto-register", "Codex")
        ):
            errors.append(f"{wrapper_path}: missing required Codex adaptation guidance")
        if "[CONNECTORS.md](../../CONNECTORS.md)" not in wrapper:
            errors.append(f"{wrapper_path}: generated Codex connector link must target ../../CONNECTORS.md")
        body = wrapper[match.end():] if match is not None else wrapper
        for raw in MARKDOWN_LINK.findall(body):
            target = raw.strip().strip("<>").split(" ", maxsplit=1)[0].split("#", maxsplit=1)[0]
            if target and not target.startswith(("/", "#", "http:", "https:", "mailto:")) and not (skill / target).is_file():
                errors.append(f"{wrapper_path}: unresolved generated link {target}")
        if skill.name.startswith("command-"):
            command_source = package / "commands" / f"{skill.name.removeprefix('command-')}.md"
            if not command_source.is_file():
                errors.append(f"{wrapper_path}: original command reference is missing")
            if f"../../commands/{command_source.name}" not in wrapper:
                errors.append(f"{wrapper_path}: original command link is missing")
        else:
            preserved = skill / "SOURCE.md"
            if not preserved.is_file() or "[SOURCE.md](SOURCE.md)" not in wrapper:
                errors.append(f"{wrapper_path}: original skill is not preserved or linked")
        if package.name == "kw-pdf-viewer" and not all(
            token in wrapper for token in ("Codex PDF", "display_pdf", "viewUUID", "not a native Codex tool")
        ):
            errors.append(f"{wrapper_path}: PDF route does not block Claude-only tools")
        if package.name == "kw-cowork-plugin-management" and not all(
            token in wrapper for token in ("Codex plugin.json", ".agents/plugins/marketplace.json", "skill-creator")
        ):
            errors.append(f"{wrapper_path}: Codex plugin or skill authoring route missing")
    return errors


def validate_packages(output_root: Path, expected_modules: tuple[str, ...]) -> list[str]:
    if not output_root.is_dir():
        return [f"{output_root}: output directory missing"]
    expected = {f"kw-{name}" for name in expected_modules}
    actual = {path.name for path in output_root.iterdir() if path.is_dir() and path.name.startswith("kw-")}
    errors = [f"Missing package: {name}" for name in sorted(expected - actual)]
    errors.extend(f"Unexpected package: {name}" for name in sorted(actual - expected))
    for name in sorted(expected & actual):
        errors.extend(validate_package(output_root / name))
    return errors


def source_link_warnings(package: Path) -> list[str]:
    warnings: list[str] = []
    generated = {"SKILL.md", "CONNECTORS.md", "NOTICE.md"}
    for document in package.rglob("*.md"):
        if document.name in generated:
            continue
        for raw in MARKDOWN_LINK.findall(document.read_text(encoding="utf-8")):
            target = raw.strip().strip("<>").split(" ", maxsplit=1)[0].split("#", maxsplit=1)[0]
            target = target.split("?", maxsplit=1)[0]
            if not target or target.startswith(("/", "#", "$", "{", "http:", "https:", "mailto:")):
                continue
            if "://" in target or re.match(r"^[a-z0-9-]+(?:\.[a-z0-9-]+){2,}/", target, re.IGNORECASE):
                continue
            if not (document.parent / target).exists():
                warnings.append(f"{document}: unresolved upstream link {target}")
    return warnings


def marketplace_errors(project: Path, expected_modules: tuple[str, ...]) -> list[str]:
    marketplace_path = project / ".agents" / "plugins" / "marketplace.json"
    try:
        marketplace = json.loads(marketplace_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return [f"{marketplace_path}: {error}"]
    if not isinstance(marketplace, dict) or not isinstance(marketplace.get("plugins"), list):
        return [f"{marketplace_path}: invalid marketplace plugins list"]
    entries = marketplace["plugins"]
    expected_names = {f"kw-{name}" for name in expected_modules}
    actual_names: set[str] = set()
    errors: list[str] = []
    for entry in entries:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
            errors.append(f"{marketplace_path}: invalid plugin entry")
            continue
        name = entry["name"]
        actual_names.add(name)
        source = entry.get("source")
        if not isinstance(source, dict) or source.get("source") != "local" or source.get("path") != f"./plugins/{name}":
            errors.append(f"{marketplace_path}: wrong local source for {name}")
    if len(entries) != len(actual_names):
        errors.append(f"{marketplace_path}: duplicate plugin entries")
    for name in sorted(expected_names - actual_names):
        errors.append(f"{marketplace_path}: missing {name}")
    for name in sorted(actual_names - expected_names):
        errors.append(f"{marketplace_path}: unexpected {name}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate the generated Codex plugin packages")
    parser.add_argument("--project", required=True, type=Path)
    args = parser.parse_args()
    packages_root = args.project / "plugins"
    if not packages_root.is_dir():
        print(f"ERROR: {packages_root}: plugin directory missing", file=sys.stderr)
        return 1
    names = EXPECTED_MODULES
    errors = validate_packages(packages_root, names)
    errors.extend(marketplace_errors(args.project, names))
    skill_count = sum(1 for package in packages_root.glob("kw-*") for _ in (package / "skills").glob("*/SKILL.md"))
    if skill_count != 186:
        errors.append(f"Expected 181 source skills plus 5 command skills; found {skill_count}")
    warnings = [warning for name in names if (packages_root / f"kw-{name}").is_dir() for warning in source_link_warnings(packages_root / f"kw-{name}")]
    for warning in warnings[:20]:
        print(f"WARNING: {warning}", file=sys.stderr)
    if len(warnings) > 20:
        print(f"WARNING: {len(warnings) - 20} more unresolved upstream links", file=sys.stderr)
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"Validated {len(names)} plugins and {skill_count} Codex skills; {len(warnings)} upstream link warnings.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
