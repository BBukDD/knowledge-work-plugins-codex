class BuildError(Exception):
    pass


def select_modules(raw: str | None) -> tuple[str, ...]:
    names = FIRST_PARTY_MODULES if raw is None else tuple(part.strip() for part in raw.split(","))
    if not names or len(names) != len(set(names)):
        raise BuildError("Module list must contain unique names.")
    for name in names:
        if name not in FIRST_PARTY_MODULES:
            raise BuildError(f"Not a permitted first-party module name: {name}")
    return names


def expected_output_modules(output_root: Path, requested: tuple[str, ...]) -> tuple[str, ...]:
    existing = {
        path.name.removeprefix("kw-")
        for path in output_root.glob("kw-*")
        if path.is_dir()
    }
    unknown = existing - set(FIRST_PARTY_MODULES)
    if unknown:
        raise BuildError(f"Unexpected generated package names: {', '.join(sorted(unknown))}")
    return tuple(name for name in FIRST_PARTY_MODULES if name in existing or name in requested)


def verify_source_revision(source_root: Path) -> None:
    head = subprocess.run(
        ["git", "-C", str(source_root), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    )
    if head.returncode != 0 or head.stdout.strip() != SOURCE_SHA:
        raise BuildError(f"Source checkout must be at pinned commit {SOURCE_SHA}: {source_root}")
    status = subprocess.run(
        [
            "git", "-C", str(source_root), "status", "--porcelain=v1",
            "--untracked-files=all", "--ignored=matching",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if status.returncode != 0 or status.stdout.strip():
        raise BuildError(f"Source checkout must be clean before packaging: {source_root}")


def copy_filter(_directory: str, names: list[str]) -> set[str]:
    forbidden = {".claude-plugin", ".mcp.json", ".git", ".DS_Store", "__pycache__", ".pytest_cache"}
    return forbidden.intersection(names)


def read_manifest(path: Path, expected_name: str) -> None:
    if not path.is_file():
        raise BuildError(f"Missing upstream plugin manifest: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("name") != expected_name:
        raise BuildError(f"Upstream plugin name mismatch: {path}")
    author = data.get("author")
    if not isinstance(author, dict) or author.get("name") != "Anthropic":
        raise BuildError(f"Module is not marked first-party by Anthropic: {path}")
    description = data.get("description")
    if not isinstance(description, str) or not description.strip():
        raise BuildError(f"Missing upstream description: {path}")


def append_package_inventory(package: Path) -> None:
    inventory: dict[str, str] = {}
    for path in sorted(package.rglob("*")):
        if path.is_symlink():
            raise BuildError(f"Symlink in generated package: {path}")
        if path.is_file() and path != package / "NOTICE.md":
            inventory[path.relative_to(package).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    notice = package / "NOTICE.md"
    write_text(
        notice,
        notice.read_text(encoding="utf-8")
        + "\n## Package integrity inventory\n\n"
        + "These SHA256 values check generated files for accidental changes. They are not a signature.\n\n"
        + INVENTORY_START
        + json.dumps(inventory, ensure_ascii=False, indent=2, sort_keys=True)
        + "\n-->\n",
    )


def build_package(source_root: Path, output_root: Path, name: str) -> tuple[int, int]:
    module = source_root / name
    if not module.is_dir():
        raise BuildError(f"Source module is missing: {module}")
    read_manifest(module / ".claude-plugin" / "plugin.json", name)
    source_skills = sorted((module / "skills").glob("*/SKILL.md"))
    if not source_skills:
        raise BuildError(f"No source skills found in {module}")
    source_commands = sorted((module / "commands").glob("*.md"))
    package = output_root / f"kw-{name}"
    shutil.copytree(module, package, ignore=copy_filter)
    try:
        adapted_scripts = apply_security_overrides(module, package, name)
    except SecurityOverrideError as error:
        raise BuildError(str(error)) from error
    original_readme = package / "README.md"
    if original_readme.is_file():
        original_readme.rename(package / "UPSTREAM_README.md")
    original_connectors = package / "CONNECTORS.md"
    source_connector_text = ""
    if original_connectors.is_file():
        source_connector_text = original_connectors.read_text(encoding="utf-8")
        original_connectors.rename(package / "UPSTREAM_CONNECTORS.md")
    license_path = package / "LICENSE"
    inherited_license = not license_path.is_file()
    if inherited_license:
        root_license = source_root / "LICENSE"
        if not root_license.is_file():
            raise BuildError(f"No Apache license found for {name}")
        shutil.copy2(Path(__file__).resolve().parents[1] / "LICENSE", license_path)
    skill_texts: list[str] = []
    for source_skill in source_skills:
        relative = source_skill.relative_to(module)
        target = package / relative
        preserved = target.with_name("SOURCE.md")
        target.rename(preserved)
        original_text = preserved.read_text(encoding="utf-8")
        skill_texts.append(original_text)
        skill_name = source_skill.parent.name
        skill_description = adapted_description(
            skill_name, name, source_description(original_text, f"Use {skill_name} workflow.")
        )
        write_text(target, render_skill(skill_name, skill_description, name))
    for source_command in source_commands:
        original_text = source_command.read_text(encoding="utf-8")
        skill_texts.append(original_text)
        command_name = f"command-{source_command.stem}"
        if (package / "skills" / command_name).exists():
            raise BuildError(f"Command skill would overwrite a source skill: {command_name}")
        command_description = adapted_description(
            command_name,
            name,
            source_description(original_text, f"Use the {source_command.stem} command workflow."),
        )
        write_text(
            package / "skills" / command_name / "SKILL.md",
            render_command(command_name, command_description, name, source_command.stem),
        )
    write_text(package / "CONNECTORS.md", render_connectors(name, source_connector_text, skill_texts))
    source_url = f"{SOURCE_REPOSITORY}/tree/{SOURCE_SHA}/{name}"
    manifest = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": f"kw-{name}",
        "version": "0.1.0",
        "description": (
            f"Unofficial Codex adaptation of Anthropic's {name} workflows. "
            f"{CODEX_MODULE_DESCRIPTIONS[name]}"
        ),
        "license": "Apache-2.0",
        "repository": source_url,
    }
    write_text(package / "plugin.json", json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    write_text(
        package / "NOTICE.md",
        f"# Attribution and adaptation\n\nOriginal workflows: Anthropic, {source_url}.\n"
        f"Source commit: `{SOURCE_SHA}`. License: Apache-2.0; see [LICENSE](LICENSE).\n\n"
        "This is an unofficial Codex adaptation. The preserved `SOURCE.md`, commands, "
        "and `UPSTREAM_CONNECTORS.md` files are original reference material. Generated "
        "`SKILL.md` and `CONNECTORS.md` files adapt their use to Codex and do not imply "
        "Anthropic endorsement or SaaS connector parity.\n"
        + (
            "\nThis upstream module has no standalone LICENSE. Its inherited upstream root "
            "license is represented here by the standard Apache-2.0 text.\n"
            if inherited_license else ""
        )
        + (
            "\nAdapted opt-in helper scripts (reviewed upstream preimages):\n"
            + "".join(f"- `{script}`\n" for script in adapted_scripts)
            if adapted_scripts else ""
        ),
    )
    write_text(package / ".codex-adapter-generated", GENERATED_MARKER)
    append_package_inventory(package)
    return len(source_skills), len(source_commands)


def build_packages(source_root: Path, output_root: Path, module_names: tuple[str, ...]) -> tuple[int, int]:
    output_root.mkdir(parents=True, exist_ok=True)
    skill_count = 0
    command_count = 0
    with tempfile.TemporaryDirectory(prefix=".kw-stage-", dir=output_root) as temporary:
        temporary_root = Path(temporary)
        stage_root = temporary_root / "new"
        stage_root.mkdir()
        backup_root = temporary_root / "backup"
        backup_root.mkdir()
        for name in module_names:
            skills, commands = build_package(source_root, stage_root, name)
            skill_count += skills
            command_count += commands
        errors = validate_packages(stage_root, module_names)
        if errors:
            raise BuildError("Staged packages failed validation: " + "; ".join(errors))
        for name in module_names:
            existing = output_root / f"kw-{name}"
            if existing.exists():
                marker = existing / ".codex-adapter-generated"
                if not existing.is_dir() or not marker.is_file() or marker.read_text(encoding="utf-8") != GENERATED_MARKER:
                    raise BuildError(f"Refusing to replace a package without the generator marker: {existing}")
        promoted: list[Path] = []
        backed_up: list[Path] = []
        try:
            for name in module_names:
                package_name = f"kw-{name}"
                existing = output_root / package_name
                if existing.exists():
                    existing.rename(backup_root / package_name)
                    backed_up.append(existing)
                (stage_root / package_name).rename(existing)
                promoted.append(existing)
        except OSError:
            for package in promoted:
                shutil.rmtree(package)
            for original in backed_up:
                (backup_root / original.name).rename(original)
            raise
    return skill_count, command_count


def package_file_hashes(output_root: Path, module_names: tuple[str, ...]) -> dict[str, str]:
    hashes: dict[str, str] = {}
    for name in module_names:
        package = output_root / f"kw-{name}"
        for path in sorted(package.rglob("*")):
            if path.is_symlink():
                raise BuildError(f"Symlink in package being checked: {path}")
            if path.is_file():
                hashes[path.relative_to(output_root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return hashes


def compare_with_fresh_build(source_root: Path, output_root: Path, module_names: tuple[str, ...]) -> list[str]:
    with tempfile.TemporaryDirectory(prefix="kw-codex-check-") as temporary:
        fresh_root = Path(temporary) / "plugins"
        build_packages(source_root, fresh_root, module_names)
        actual = package_file_hashes(output_root, module_names)
        fresh = package_file_hashes(fresh_root, module_names)
    return [
        f"{output_root / relative}: differs from clean pinned source"
        for relative in sorted(actual.keys() | fresh.keys())
        if actual.get(relative) != fresh.get(relative)
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description="Build unofficial Codex packages from pinned Anthropic source")
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--modules", help="Comma-separated explicit module subset; defaults to the 17 first-party modules")
    parser.add_argument("--check", action="store_true", help="Validate existing output without rebuilding")
    args = parser.parse_args()
    try:
        modules = select_modules(args.modules)
        expected = expected_output_modules(args.output, modules)
        verify_source_revision(args.source)
        if args.check:
            skills = commands = 0
        else:
            if args.modules is not None and args.output.is_dir():
                existing = tuple(name for name in expected if (args.output / f"kw-{name}").is_dir())
                baseline_errors = validate_packages(args.output, existing)
                if baseline_errors:
                    raise BuildError("Existing packages must validate before a subset rebuild: " + "; ".join(baseline_errors))
            skills, commands = build_packages(args.source, args.output, modules)
        errors = validate_packages(args.output, expected)
        if not errors and args.check:
            errors.extend(compare_with_fresh_build(args.source, args.output, expected))
        if errors:
            for error in errors:
                print(f"ERROR: {error}", file=sys.stderr)
            return 1
    except (BuildError, OSError, json.JSONDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"Validated {len(expected)} plugins, {skills} source skills rebuilt, {commands} command skills rebuilt.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
